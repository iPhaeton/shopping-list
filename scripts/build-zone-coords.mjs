#!/usr/bin/env node
/**
 * Generates src/lib/zoneCoords.ts — where each IANA time zone's principal city is — from an
 * unpacked tzdata release:
 *
 *     curl -sSfLO https://data.iana.org/time-zones/releases/tzdata2026c.tar.gz
 *     mkdir tzdata && tar xzf tzdata2026c.tar.gz -C tzdata
 *     node scripts/build-zone-coords.mjs tzdata
 *
 * Auto theme reads the device's zone name and needs somewhere to compute sunset for. Two tzdata
 * files, deliberately:
 *
 * - `zone.tab`, not `zone1970.tab`. The latter folds zones that have agreed since 1970 into one
 *   (Europe/Oslo into Europe/Berlin), which would put Oslo's sunset at Berlin's.
 * - `backward`, for legacy names a device may still report (Asia/Calcutta → Asia/Kolkata). A name
 *   in `zone.tab` always keeps its own city, even where `backward` links it elsewhere. A link whose
 *   target has no city (UTC, Etc/*) is left out, and the app falls back to fixed hours for it.
 *
 * Deliberately dependency-free, like kb-audit.mjs.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/lib/zoneCoords.ts');

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-zone-coords.mjs <unpacked tzdata dir>');
  process.exit(1);
}

const read = (name) => readFileSync(path.join(dir, name), 'utf8');
const version = read('version').trim();

/** ISO 6709 as zone.tab writes it: ±DDMM±DDDMM or ±DDMMSS±DDDMMSS. */
function parseCoordinates(text) {
  const match = text.match(/^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/);
  if (!match) throw new Error(`unreadable coordinates: ${text}`);
  const [, latSign, latD, latM, latS = '0', lonSign, lonD, lonM, lonS = '0'] = match;
  const degrees = (sign, d, m, s) => (sign === '-' ? -1 : 1) * (+d + +m / 60 + +s / 3600);
  const round = (value) => Math.round(value * 100) / 100;
  return [round(degrees(latSign, latD, latM, latS)), round(degrees(lonSign, lonD, lonM, lonS))];
}

const coords = new Map();
for (const line of read('zone.tab').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coordinates, zone] = line.split('\t');
  coords.set(zone, parseCoordinates(coordinates));
}
const canonical = coords.size;

/**
 * `Link TARGET NAME`, sometimes followed by `#= BETTER`: the target the link would have if old
 * parsers could follow links to links. It is the nearer city (Iceland's is Reykjavik, not the
 * Abidjan it formally links to), so it is tried first.
 */
const links = [];
for (const line of read('backward').split('\n')) {
  const match = line.match(/^Link\s+(\S+)\s+(\S+)(?:\s+#=\s*(\S+))?/);
  if (match) links.push({ name: match[2], targets: [match[3], match[1]].filter(Boolean) });
}

// A target may itself be a link; repeat until nothing new resolves.
let pending = links.filter((link) => !coords.has(link.name));
for (let resolved = true; resolved; ) {
  resolved = false;
  pending = pending.filter((link) => {
    const target = link.targets.find((candidate) => coords.has(candidate));
    if (!target) return true;
    coords.set(link.name, coords.get(target));
    resolved = true;
    return false;
  });
}

const entries = [...coords.keys()]
  .sort()
  .map((zone) => `  '${zone}': [${coords.get(zone).join(', ')}],`)
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/build-zone-coords.mjs from tzdata ${version} — do not edit by hand.
// ${canonical} zones from zone.tab, ${coords.size - canonical} legacy names from backward.
// Names with no city (UTC, Etc/*, and the ${pending.length} links to them) are absent on purpose.

/** IANA zone → [latitude, longitude] of its principal city, in degrees (north and east positive). */
export const ZONE_COORDS: Readonly<Record<string, readonly [number, number]>> = {
${entries}
};
`
);

console.log(
  `tzdata ${version}: ${canonical} zones + ${coords.size - canonical} links → ${path.relative(ROOT, OUT)}; ` +
    `left out: ${pending.map((link) => link.name).join(', ')}`
);
